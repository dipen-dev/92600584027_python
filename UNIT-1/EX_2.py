# 2. Program to demonstrate different data types and type casting

name = "Dipen"
age = 20
height = 5.8
student = True

print("Name:", name)
print("Type of name:", type(name))
print("Age:", age)
print("Type of age:", type(age))
print("Height:", height)
print("Type of height:", type(height))
print("Student:", student)
print("Type of student:", type(student))

num1 = "25"
num2 = int(num1)

num3 = 10
num4 = float(num3)

num5 = 50
num6 = str(num5)

print("String to Integer:", num2)
print("Integer to Float:", num4)
print("Integer to String:", num6)